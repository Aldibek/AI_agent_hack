def reviewer_system(variant: int = 0) -> str:
    focus = FOCUS.get(variant, FOCUS[0])
    schema = FINDING_SCHEMA
    if variant == 0:
        schema = schema.rstrip("}").rstrip() + ',\n  "coverage": [[1, 0, 3], [2, 1, 1]]\n}'
    return f"""{INTRO}

{criteria_prompt_block()}

{CATEGORY_NOTES}

{focus}

{RULES}

Ответ — строго один JSON-объект такой структуры:
{schema}"""


